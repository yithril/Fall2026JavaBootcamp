package org.example;

public class ForExample {
    public static void main(String[] args) {
        //specific number of times you'd like to do something

        for(int i = 0; i < 5; i++){
            System.out.println("i is equal to: " + i);
        } //i++

        for(int j = 20; j > 0; j--){
            System.out.println("j is equal to: " + j);
        }//j--
    }
}
